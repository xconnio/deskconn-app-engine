"""Generates the named icons, web/src/icons.ts and dart/lib/src/icons.dart, from names.txt.

The web renderer's paths come from Material Icons' filled SVGs (Apache-2.0):

    npm pack @material-design-icons/svg@0.14.15 && tar xzf material-design-icons-svg-0.14.15.tgz
    python3 icons/generate.py package/filled
"""
import re, sys, pathlib
svg_dir = pathlib.Path(sys.argv[1])
repo = pathlib.Path(__file__).resolve().parent.parent
names_file = repo / 'icons/names.txt'
names = [n for line in names_file.read_text().splitlines() if not line.startswith('#') for n in line.split()]
assert len(names) == len(set(names)), 'duplicate names'
paths = {}
for name in names:
    svg = (svg_dir / f'{name}.svg').read_text()
    ds = re.findall(r'<path d="([^"]*)"/>', svg)
    for cx, cy, r in re.findall(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"/>', svg):
        cx, cy, r = float(cx), float(cy), float(r)
        ds.insert(0, f'M{cx - r:g} {cy:g}a{r:g} {r:g} 0 1 0 {2 * r:g} 0a{r:g} {r:g} 0 1 0 {-2 * r:g} 0z')
    assert ds and len(re.findall(r'<(?!svg|/svg)[a-z]+', svg)) == len(ds), name
    paths[name] = ds

header = ("Material Icons (Apache-2.0, https://fonts.google.com/icons), filled, by name: the icons a\n"
          "manifest can name, e.g. `icon: play_arrow`. Generated by icons/generate.py from\n"
          "icons/names.txt, which the Dart and web renderers share: add a name there when an app\n"
          "needs one.")
ts = ['// ' + l for l in header.splitlines()]
ts += ['// Each is SVG paths on a 24×24 view box.', 'export const manifestIcons: Readonly<Record<string, readonly string[]>> = {']
for name in names:
    ts.append(f"  {name}: [{', '.join(repr(d) for d in paths[name])}],")
ts.append('}\n')
(repo / 'web/src/icons.ts').write_text('\n'.join(ts))

dart = ['/// ' + l for l in header.splitlines()]
dart += ['library;', '', "import 'package:flutter/material.dart';", '',
         '/// Flutter\'s [Icons] for the names a manifest can use.',
         'const Map<String, IconData> manifestIcons = {']
dart += [f"  '{name}': Icons.{name}," for name in names]
dart.append('};\n')
(repo / 'dart/lib/src/icons.dart').write_text('\n'.join(dart))
print(len(names), 'icons')
